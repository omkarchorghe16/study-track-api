-- Shared catalog of study tracks (for example "Full-Stack Java Developer"), their subjects and topic trees.
-- Only an admin changes it (CSV import); every user can browse it and copy a subject into their own subjects.
-- Questions are not part of the catalog yet.
ALTER TABLE study_track.users ADD COLUMN is_admin BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE study_track.users SET is_admin = TRUE WHERE id = 1;

CREATE TABLE study_track.catalog_tracks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    description VARCHAR(1000),
    sort_order  INT           NOT NULL DEFAULT 0,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_catalog_tracks_name UNIQUE (name)
);

CREATE TABLE study_track.catalog_subjects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id    BIGINT        NOT NULL REFERENCES study_track.catalog_tracks (id) ON DELETE CASCADE,
    name        VARCHAR(120)  NOT NULL,
    description VARCHAR(1000),
    icon        VARCHAR(16),
    sort_order  INT           NOT NULL DEFAULT 0,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_catalog_subjects_track_name UNIQUE (track_id, name)
);
CREATE INDEX idx_catalog_subjects_track_id ON study_track.catalog_subjects (track_id);

CREATE TABLE study_track.catalog_topics (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_subject_id BIGINT        NOT NULL REFERENCES study_track.catalog_subjects (id) ON DELETE CASCADE,
    parent_id          BIGINT        REFERENCES study_track.catalog_topics (id) ON DELETE CASCADE,
    name               VARCHAR(200)  NOT NULL,
    sort_order         INT           NOT NULL DEFAULT 0,
    created_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_catalog_topics_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX idx_catalog_topics_subject_id ON study_track.catalog_topics (catalog_subject_id);
CREATE INDEX idx_catalog_topics_parent_id ON study_track.catalog_topics (parent_id);

-- The catalog subject a user's subject was copied from; kept when the catalog subject is deleted.
ALTER TABLE study_track.subjects
    ADD COLUMN catalog_subject_id BIGINT REFERENCES study_track.catalog_subjects (id) ON DELETE SET NULL;
CREATE INDEX idx_subjects_catalog_subject_id ON study_track.subjects (catalog_subject_id);

COMMENT ON COLUMN study_track.users.is_admin IS 'True for users who may change the shared catalog (CSV import).';
COMMENT ON TABLE study_track.catalog_tracks IS 'Shared study tracks such as "Full-Stack Java Developer"; each groups catalog subjects.';
COMMENT ON COLUMN study_track.catalog_tracks.id IS 'Primary key.';
COMMENT ON COLUMN study_track.catalog_tracks.name IS 'Track name, unique.';
COMMENT ON COLUMN study_track.catalog_tracks.description IS 'Optional short description.';
COMMENT ON COLUMN study_track.catalog_tracks.sort_order IS 'Position among tracks, ascending.';
COMMENT ON COLUMN study_track.catalog_tracks.created_at IS 'When the track was added.';
COMMENT ON TABLE study_track.catalog_subjects IS 'Shared subjects of a track (for example Core Java); a user copies one into their own subjects.';
COMMENT ON COLUMN study_track.catalog_subjects.id IS 'Primary key.';
COMMENT ON COLUMN study_track.catalog_subjects.track_id IS 'Track this subject belongs to; deleting the track deletes the subject.';
COMMENT ON COLUMN study_track.catalog_subjects.name IS 'Subject name, unique within the track.';
COMMENT ON COLUMN study_track.catalog_subjects.description IS 'Optional short description.';
COMMENT ON COLUMN study_track.catalog_subjects.icon IS 'Optional emoji shown on the subject card.';
COMMENT ON COLUMN study_track.catalog_subjects.sort_order IS 'Position within the track, ascending.';
COMMENT ON COLUMN study_track.catalog_subjects.created_at IS 'When the subject was added.';
COMMENT ON TABLE study_track.catalog_topics IS 'Shared topic tree of a catalog subject (topics, subtopics, and so on).';
COMMENT ON COLUMN study_track.catalog_topics.id IS 'Primary key.';
COMMENT ON COLUMN study_track.catalog_topics.catalog_subject_id IS 'Catalog subject the topic belongs to; deleting the subject deletes its topics.';
COMMENT ON COLUMN study_track.catalog_topics.parent_id IS 'Parent topic; null for a top-level topic.';
COMMENT ON COLUMN study_track.catalog_topics.name IS 'Topic name.';
COMMENT ON COLUMN study_track.catalog_topics.sort_order IS 'Position among siblings, ascending.';
COMMENT ON COLUMN study_track.catalog_topics.created_at IS 'When the topic was added.';
COMMENT ON COLUMN study_track.subjects.catalog_subject_id IS 'Catalog subject this subject was copied from; null for subjects the user created.';
