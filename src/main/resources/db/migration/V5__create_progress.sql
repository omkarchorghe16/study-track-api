-- Study progress of each user. A missing item_progress row means NOT_STARTED.
CREATE TABLE item_progress (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL REFERENCES users (id),
    item_id          BIGINT      NOT NULL REFERENCES study_items (id) ON DELETE CASCADE,
    status           VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',
    confidence       SMALLINT,
    review_count     INT         NOT NULL DEFAULT 0,
    last_reviewed_at TIMESTAMP,
    next_review_at   TIMESTAMP,
    bookmarked       BOOLEAN     NOT NULL DEFAULT FALSE,
    updated_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_item_progress_user_item UNIQUE (user_id, item_id),
    CONSTRAINT ck_item_progress_status CHECK (status IN ('NOT_STARTED', 'LEARNING', 'DONE')),
    CONSTRAINT ck_item_progress_confidence CHECK (confidence IS NULL OR confidence BETWEEN 1 AND 5),
    CONSTRAINT ck_item_progress_review_count CHECK (review_count >= 0)
);

CREATE INDEX idx_item_progress_item_id ON item_progress (item_id);
CREATE INDEX idx_item_progress_user_next_review ON item_progress (user_id, next_review_at);

-- Manual "mark complete" for a topic. A topic also shows as complete (as a hint) when all its items are DONE.
CREATE TABLE topic_progress (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT    NOT NULL REFERENCES users (id),
    topic_id     BIGINT    NOT NULL REFERENCES topics (id) ON DELETE CASCADE,
    completed    BOOLEAN   NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMP,
    CONSTRAINT uq_topic_progress_user_topic UNIQUE (user_id, topic_id)
);

CREATE INDEX idx_topic_progress_topic_id ON topic_progress (topic_id);

-- One row per flashcard rating; feeds the scheduler, the streak and the activity chart.
CREATE TABLE review_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    item_id     BIGINT      NOT NULL REFERENCES study_items (id) ON DELETE CASCADE,
    result      VARCHAR(10) NOT NULL,
    reviewed_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_review_log_result CHECK (result IN ('AGAIN', 'HARD', 'GOOD', 'EASY'))
);

CREATE INDEX idx_review_log_user_reviewed_at ON review_log (user_id, reviewed_at);
CREATE INDEX idx_review_log_item_id ON review_log (item_id, reviewed_at);

-- "Continue where you left off": the last topic and item opened, one row per user and subject.
CREATE TABLE study_sessions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT    NOT NULL REFERENCES users (id),
    subject_id    BIGINT    NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    last_topic_id BIGINT    REFERENCES topics (id) ON DELETE SET NULL,
    last_item_id  BIGINT    REFERENCES study_items (id) ON DELETE SET NULL,
    updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_study_sessions_user_subject UNIQUE (user_id, subject_id)
);

CREATE INDEX idx_study_sessions_user_updated_at ON study_sessions (user_id, updated_at);
