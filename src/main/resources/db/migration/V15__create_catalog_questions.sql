-- Starter questions and answers of the shared catalog, under a catalog topic. Plain text; the answer may use
-- blank lines for paragraphs, "- " lines for lists, `code` and ``` fenced blocks. Copied into a user's
-- questions (source CATALOG) when the user adds the catalog subject.
CREATE TABLE study_track.catalog_questions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_topic_id BIGINT        NOT NULL REFERENCES study_track.catalog_topics (id) ON DELETE CASCADE,
    question         VARCHAR(1000) NOT NULL,
    answer           TEXT,
    difficulty       VARCHAR(10)   NOT NULL DEFAULT 'MEDIUM',
    sort_order       INT           NOT NULL DEFAULT 0,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_catalog_questions_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD'))
);
CREATE INDEX idx_catalog_questions_topic_id ON study_track.catalog_questions (catalog_topic_id);

ALTER TABLE study_track.questions DROP CONSTRAINT ck_questions_source;
ALTER TABLE study_track.questions ADD CONSTRAINT ck_questions_source CHECK (source IN ('MANUAL', 'IMPORT', 'CATALOG'));

COMMENT ON TABLE study_track.catalog_questions IS 'Shared starter questions and answers of a catalog topic; copied to a user when they add the catalog subject.';
COMMENT ON COLUMN study_track.catalog_questions.id IS 'Primary key.';
COMMENT ON COLUMN study_track.catalog_questions.catalog_topic_id IS 'Catalog topic the question belongs to; deleting the topic deletes its questions.';
COMMENT ON COLUMN study_track.catalog_questions.question IS 'The question as plain text.';
COMMENT ON COLUMN study_track.catalog_questions.answer IS 'The answer as plain text (blank lines, "- " lists, `code` and ``` blocks).';
COMMENT ON COLUMN study_track.catalog_questions.difficulty IS 'EASY, MEDIUM or HARD.';
COMMENT ON COLUMN study_track.catalog_questions.sort_order IS 'Position within the topic, ascending.';
COMMENT ON COLUMN study_track.catalog_questions.created_at IS 'When the question was added.';
COMMENT ON COLUMN study_track.questions.source IS 'MANUAL (typed in the app), IMPORT (approved from an import) or CATALOG (copied from the shared catalog).';
