-- Document imports. A job is one uploaded file (stored as a media_files row); the LLM turns its
-- chunks into candidates, which become study_items only when the user approves them.
CREATE TABLE import_jobs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL REFERENCES users (id),
    subject_id       BIGINT        NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    file_name        VARCHAR(255)  NOT NULL,
    file_type        VARCHAR(10)   NOT NULL,
    media_id         BIGINT        REFERENCES media_files (id) ON DELETE SET NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'UPLOADED',
    llm_provider     VARCHAR(20)   NOT NULL,
    llm_model        VARCHAR(100)  NOT NULL,
    total_chunks     INT           NOT NULL DEFAULT 0,
    processed_chunks INT           NOT NULL DEFAULT 0,
    -- Chunks whose LLM answer was still invalid after one retry; their text produced no candidates.
    failed_chunks    INT           NOT NULL DEFAULT 0,
    input_tokens     BIGINT        NOT NULL DEFAULT 0,
    output_tokens    BIGINT        NOT NULL DEFAULT 0,
    error_message    VARCHAR(1000),
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_import_jobs_file_type CHECK (file_type IN ('DOCX', 'PDF', 'MD', 'TXT')),
    CONSTRAINT ck_import_jobs_status CHECK (status IN ('UPLOADED', 'PARSING', 'EXTRACTING', 'READY_FOR_REVIEW',
                                                       'COMPLETED', 'FAILED')),
    CONSTRAINT ck_import_jobs_provider CHECK (llm_provider IN ('ANTHROPIC', 'OPENAI', 'OLLAMA'))
);

CREATE INDEX idx_import_jobs_user_created_at ON import_jobs (user_id, created_at);
CREATE INDEX idx_import_jobs_subject_id ON import_jobs (subject_id);

-- One question, note or example the LLM found. HTML columns are sanitised and reference images as
-- <img src="/api/v1/media/{id}">. content_hash matches study_items.content_hash to flag duplicates.
CREATE TABLE import_candidates (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id               BIGINT       NOT NULL REFERENCES import_jobs (id) ON DELETE CASCADE,
    chunk_index          INT          NOT NULL,
    suggested_topic_path VARCHAR(500),
    item_type            VARCHAR(20)  NOT NULL,
    title                VARCHAR(300) NOT NULL,
    question_html        TEXT,
    answer_html          TEXT,
    notes_html           TEXT,
    difficulty           VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM',
    -- Comma-separated, lower-case tag names.
    tags                 VARCHAR(1000),
    -- Comma-separated media ids the candidate's HTML uses.
    image_refs           VARCHAR(1000),
    confidence_score     NUMERIC(4, 3),
    content_hash         VARCHAR(64),
    status               VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    target_topic_id      BIGINT       REFERENCES topics (id) ON DELETE SET NULL,
    created_item_id      BIGINT       REFERENCES study_items (id) ON DELETE SET NULL,
    sort_order           INT          NOT NULL DEFAULT 0,
    CONSTRAINT ck_import_candidates_type CHECK (item_type IN ('QUESTION', 'NOTE', 'EXAMPLE', 'DIAGRAM')),
    CONSTRAINT ck_import_candidates_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    CONSTRAINT ck_import_candidates_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'EDITED')),
    CONSTRAINT ck_import_candidates_confidence CHECK (confidence_score IS NULL
                                                      OR confidence_score BETWEEN 0 AND 1)
);

CREATE INDEX idx_import_candidates_job_id ON import_candidates (job_id, sort_order);

ALTER TABLE study_items
    ADD CONSTRAINT fk_study_items_import_job FOREIGN KEY (import_job_id) REFERENCES import_jobs (id) ON DELETE SET NULL;
