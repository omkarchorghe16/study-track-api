-- Subjects are a user's courses or prep tracks; topics form a tree inside a subject.
CREATE TABLE subjects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (id),
    name        VARCHAR(120)  NOT NULL,
    description VARCHAR(1000),
    icon        VARCHAR(16),
    sort_order  INT           NOT NULL DEFAULT 0,
    archived    BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_subjects_user_name UNIQUE (user_id, name)
);

-- parent_id is null for top-level topics. Deleting a subject or a topic deletes its subtopics.
CREATE TABLE topics (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id       BIGINT       NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    parent_id        BIGINT       REFERENCES topics (id) ON DELETE CASCADE,
    name             VARCHAR(200) NOT NULL,
    description_html TEXT,
    sort_order       INT          NOT NULL DEFAULT 0,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_topics_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX idx_topics_subject_id ON topics (subject_id);
CREATE INDEX idx_topics_parent_id ON topics (parent_id);
