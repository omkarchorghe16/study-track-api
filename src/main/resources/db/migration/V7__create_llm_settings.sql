-- The LLM each user imports with. Missing row = the defaults under app.llm in application.yml.
-- API keys are never stored here: they come from ANTHROPIC_API_KEY / OPENAI_API_KEY.
CREATE TABLE llm_settings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    provider   VARCHAR(20)  NOT NULL,
    model      VARCHAR(100) NOT NULL,
    base_url   VARCHAR(500),
    enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_llm_settings_user UNIQUE (user_id),
    CONSTRAINT ck_llm_settings_provider CHECK (provider IN ('ANTHROPIC', 'OPENAI', 'OLLAMA'))
);
