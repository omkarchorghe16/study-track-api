-- Uploaded images. The file lives in media storage under storage_key (a local path now, an S3 key later);
-- HTML references it as <img src="/api/v1/media/{id}">, never as base64.
-- item_id is set once the image is used in a saved item; deleting the item keeps the row (SET NULL) and
-- ItemService deletes the files of items it removes.
CREATE TABLE media_files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id),
    item_id       BIGINT       REFERENCES study_items (id) ON DELETE SET NULL,
    original_name VARCHAR(255) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    storage_key   VARCHAR(500) NOT NULL,
    width         INT,
    height        INT,
    alt_text      VARCHAR(500),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_media_files_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_media_files_size CHECK (size_bytes > 0)
);

CREATE INDEX idx_media_files_user_id ON media_files (user_id);
CREATE INDEX idx_media_files_item_id ON media_files (item_id);
