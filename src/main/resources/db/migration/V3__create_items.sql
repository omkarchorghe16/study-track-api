-- Questions, notes, examples and diagrams inside a topic. HTML columns hold editor output;
-- answer_plain is the answer without tags, for search and AI features.
CREATE TABLE study_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id      BIGINT       NOT NULL REFERENCES topics (id) ON DELETE CASCADE,
    item_type     VARCHAR(20)  NOT NULL,
    title         VARCHAR(300) NOT NULL,
    question_html TEXT,
    answer_html   TEXT,
    notes_html    TEXT,
    answer_plain  TEXT,
    difficulty    VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM',
    source        VARCHAR(10)  NOT NULL DEFAULT 'MANUAL',
    -- References import_jobs once the import tables exist (V6 adds the foreign key).
    import_job_id BIGINT,
    -- SHA-256 of the normalised question text, used to spot duplicates.
    content_hash  VARCHAR(64),
    sort_order    INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_study_items_type CHECK (item_type IN ('QUESTION', 'NOTE', 'EXAMPLE', 'DIAGRAM')),
    CONSTRAINT ck_study_items_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    CONSTRAINT ck_study_items_source CHECK (source IN ('MANUAL', 'IMPORT'))
);

CREATE INDEX idx_study_items_topic_id ON study_items (topic_id);
CREATE INDEX idx_study_items_content_hash ON study_items (content_hash);

-- Tag names are stored lower-case and are unique per user.
CREATE TABLE tags (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT      NOT NULL REFERENCES users (id),
    name    VARCHAR(50) NOT NULL,
    CONSTRAINT uq_tags_user_name UNIQUE (user_id, name)
);

CREATE TABLE study_item_tags (
    item_id BIGINT NOT NULL REFERENCES study_items (id) ON DELETE CASCADE,
    tag_id  BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    CONSTRAINT pk_study_item_tags PRIMARY KEY (item_id, tag_id)
);

CREATE INDEX idx_study_item_tags_tag_id ON study_item_tags (tag_id);
