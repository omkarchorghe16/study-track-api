-- AI-written detailed explanation of a question (summary, key points, steps, code example, real-world example,
-- common mistakes, interview tip). Kept next to the question's own answer, never replacing it. content is JSON
-- that the app renders as text, so no HTML from the model is ever stored.
CREATE TABLE study_track.question_explanations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  BIGINT       NOT NULL REFERENCES study_track.questions (id) ON DELETE CASCADE,
    user_id      BIGINT       NOT NULL REFERENCES study_track.users (id),
    content      TEXT         NOT NULL,
    llm_provider VARCHAR(20)  NOT NULL,
    llm_model    VARCHAR(100) NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_question_explanations_question UNIQUE (question_id)
);
CREATE INDEX idx_question_explanations_user_id ON study_track.question_explanations (user_id);

COMMENT ON TABLE study_track.question_explanations IS 'AI-written detailed explanation of a question, shown next to its own answer.';
COMMENT ON COLUMN study_track.question_explanations.id IS 'Primary key.';
COMMENT ON COLUMN study_track.question_explanations.question_id IS 'The explained question; one explanation per question, deleted with it.';
COMMENT ON COLUMN study_track.question_explanations.user_id IS 'Owner of the question.';
COMMENT ON COLUMN study_track.question_explanations.content IS 'JSON: summary, analogy, keyPoints, howItWorks, example, realWorldExample, commonMistakes, interviewTip.';
COMMENT ON COLUMN study_track.question_explanations.llm_provider IS 'LLM provider that wrote it (ANTHROPIC, OPENAI, GROQ, OLLAMA).';
COMMENT ON COLUMN study_track.question_explanations.llm_model IS 'LLM model id that wrote it.';
COMMENT ON COLUMN study_track.question_explanations.created_at IS 'When it was first generated.';
COMMENT ON COLUMN study_track.question_explanations.updated_at IS 'When it was last regenerated.';
