-- Explanations become shared: one AI-written explanation per question (identified by subject name and question
-- text), read by every user, so the AI is called only when nothing is saved yet. V16's per-user table is replaced;
-- it only ever held explanations written by the feature's first version.
DROP TABLE study_track.question_explanations;

CREATE TABLE study_track.shared_explanations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    explanation_key VARCHAR(64)  NOT NULL,
    content         TEXT         NOT NULL,
    llm_provider    VARCHAR(20)  NOT NULL,
    llm_model       VARCHAR(100) NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_shared_explanations_key UNIQUE (explanation_key)
);

COMMENT ON TABLE study_track.shared_explanations IS 'AI-written detailed explanation of a question, shared by all users and found by explanation_key.';
COMMENT ON COLUMN study_track.shared_explanations.id IS 'Primary key.';
COMMENT ON COLUMN study_track.shared_explanations.explanation_key IS 'SHA-256 of the normalised subject name and question text; the same question in the same subject shares one explanation.';
COMMENT ON COLUMN study_track.shared_explanations.content IS 'JSON: summary, analogy, keyPoints, howItWorks, example, realWorldExample, commonMistakes, interviewTip (plain text, never HTML).';
COMMENT ON COLUMN study_track.shared_explanations.llm_provider IS 'LLM provider that wrote it (ANTHROPIC, OPENAI, GROQ, OLLAMA).';
COMMENT ON COLUMN study_track.shared_explanations.llm_model IS 'LLM model id that wrote it.';
COMMENT ON COLUMN study_track.shared_explanations.created_at IS 'When it was first generated.';
COMMENT ON COLUMN study_track.shared_explanations.updated_at IS 'When it was last changed.';
