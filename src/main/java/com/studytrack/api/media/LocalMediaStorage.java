package com.studytrack.api.media;

import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;

/** Stores files under {@code app.media.storage-dir}; keys are relative paths such as {@code 2026/11/uuid.png}. */
@Component
public class LocalMediaStorage implements MediaStorage {
    private final Path rootDirectory;

    public LocalMediaStorage(MediaProperties mediaProperties) {
        this.rootDirectory = Path.of(mediaProperties.storageDir()).toAbsolutePath().normalize();
    }

    @Override
    public void storeFile(String storageKey, byte[] content) throws IOException {
        Path target = resolve(storageKey);
        Files.createDirectories(target.getParent());
        Files.write(target, content, StandardOpenOption.CREATE_NEW);
    }

    @Override
    public InputStream openFile(String storageKey) throws IOException {
        return Files.newInputStream(resolve(storageKey));
    }

    @Override
    public void deleteFile(String storageKey) throws IOException {
        Files.deleteIfExists(resolve(storageKey));
    }

    /** Keys are generated by MediaService, but a key that escapes the root directory is still refused. */
    private Path resolve(String storageKey) {
        Path path = rootDirectory.resolve(storageKey).normalize();
        if (!path.startsWith(rootDirectory)) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        return path;
    }
}
